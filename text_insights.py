def extract_frequent_terms(text: str) -> list[tuple[str, int]]:
    """Return up to three non-common words with the highest local counts."""
    words = [
        match.group(0).casefold()
        for match in _WORDS.finditer(text)
        if len(match.group(0).replace("'", "").replace("’", "")) > 2
    ]
    counts = Counter(word for word in words if word not in _COMMON_WORDS)
    return counts.most_common(3)
